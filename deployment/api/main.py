# ------------------------------------------------------------------ helpers
def haversine_km(lat1, lon1, lat2, lon2):
    """Great-circle distance, as src/features.py computes it for the training data."""
    lat1, lon1, lat2, lon2 = map(np.radians, [lat1, lon1, lat2, lon2])
    a = np.sin((lat2 - lat1) / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin((lon2 - lon1) / 2) ** 2
    return float(2 * 6371.0 * np.arcsin(np.sqrt(a)))


def locate(zip_text, state, who, notes):
    """(lat, lng, state, from_zip) for one party: its zip prefix if known, else the centre of its state."""
    if zip_text is None:
        return (*STATE_CENTRE[state], state, False)
    z = int(zip_text)
    same = ZIP_BY_REGION.get(z // 100)
    if same is None:
        notes.append(f"{who} zip {z:05d} is not in the Olist zip table: using the centre of {state}.")
        return (*STATE_CENTRE[state], state, False)
    near = int(same[np.abs(same - z).argmin()])
    lat, lng, zstate = ZIP_ROW[near]
    if near != z:
        notes.append(f"{who} zip {z:05d} is not in the Olist zip table: using the nearest one, {near:05d}.")
    if zstate != state:
        notes.append(f"{who} zip {near:05d} is in {zstate}, not {state}: using {zstate}.")
    return lat, lng, zstate, True


def resolve_route(r):
    """States, distance and same-state flag for one request row, with notes on how they were derived."""
    notes = []
    s_lat, s_lng, s_state, s_zip = locate(r.seller_zip, r.seller_state, "Seller", notes)
    c_lat, c_lng, c_state, c_zip = locate(r.customer_zip, r.customer_state, "Customer", notes)
    if "distance_km" in r.model_fields_set:
        dist = r.distance_km
        if dist is None:
            notes.append("Distance unknown: the models use the training median.")
    else:
        dist = haversine_km(s_lat, s_lng, c_lat, c_lng)
        if not (s_zip and c_zip):
            where = lambda used, st: "zip code" if used else f"centre of {st}"
            notes.append(f"Distance measured from the seller's {where(s_zip, s_state)} to the customer's "
                         f"{where(c_zip, c_state)}.")
    if r.model_extra:
        notes.append("Ignored input(s) the models do not use: " + ", ".join(sorted(r.model_extra)) + ".")
    return dict(seller_state=s_state, customer_state=c_state, distance_km=dist,
                same_state=int(s_state == c_state)), notes


def model_frame(rows, columns):
    """The pipelines' input frame. order_id and purchase_ts are split keys of the training code, not model inputs."""
    X = pd.DataFrame(rows).assign(order_id="api", purchase_ts=0.0)
    X["distance_km"] = pd.to_numeric(X["distance_km"]).astype(float)        # None -> NaN: imputed by the pipeline
    return X[columns]


def drift(X, problem):
    """Per row: (inputs flagged, warnings) for numeric inputs > 3 sd from the training mean, counts above the training
    maximum and categories not seen in training."""
    stats, z = STATS[problem], STATS["z"]
    flagged = [[] for _ in range(len(X))]
    warnings = [[] for _ in range(len(X))]
    for c, s in stats["numeric"].items():
        x = X[c].to_numpy(dtype=float)
        if s["scale"] == "count":                                         # mostly 1: flag only beyond the training max
            for i in np.flatnonzero(x > s["max"]):
                flagged[i].append(c)
                warnings[i].append(f"{c} = {x[i]:.0f} is above the largest value seen in training ({s['max']})")
            continue
        v = np.log1p(np.clip(x, 0, None)) if s["scale"] == "log1p" else x
        dev = (v - s["mean"]) / s["std"]
        for i in np.flatnonzero(np.abs(dev) > z):                         # NaN compares False: never flagged
            side, bound = ("above", s["high"]) if dev[i] > 0 else ("below", s["low"])
            scale = " on the log scale" if s["scale"] == "log1p" else ""
            flagged[i].append(c)
            warnings[i].append(f"{c} = {x[i]:,.2f} is {side} the training mean {'+' if dev[i] > 0 else '-'} 3 sd"
                               f"{scale} ({bound:,.2f}): the model has seen few cases like this")
    for c, counts in stats["categorical"].items():
        for i, v in enumerate(X[c].astype(str)):
            if v not in counts:
                flagged[i].append(c)
                warnings[i].append(f"{c} '{v}' was not seen in training: the model treats it as a rare value")
    return flagged, warnings


def rare_notes(X, problem):
    """Categories seen in training too rarely to have their own level: the encoder pools them."""
    out = [[] for _ in range(len(X))]
    for c, counts in STATS[problem]["categorical"].items():
        for i, v in enumerate(X[c].astype(str)):
            n = counts.get(v, 0)
            if 0 < n < STATS["min_frequency"]:
                out[i].append(f"{c} '{v}' had only {n} training rows: the model pools it with other rare values.")
    return out


def plain(v):
    """JSON-safe scalar (NaN -> None)."""
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (float, np.floating)):
        return None if np.isnan(v) else float(v)
    return v


def field_ranges(model):
    """The numeric bounds Pydantic enforces on a schema, for /model-info."""
    out = {}
    for name, f in model.model_fields.items():
        b = {k: getattr(m, k) for m in f.metadata for k in ("gt", "ge", "lt", "le") if getattr(m, k, None) is not None}
        if b:
            out[name] = b
    return out


def new_request():
    return f"req_{datetime.now(timezone.utc):%Y%m%d_%H%M%S}_{uuid.uuid4().hex[:6]}", time.perf_counter()


def stamp(request_id, t0):
    return dict(request_id=request_id, timestamp=datetime.now(timezone.utc).isoformat(timespec="seconds"),
                latency_ms=round((time.perf_counter() - t0) * 1000, 1))


