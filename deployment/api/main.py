def _absorb(entry):
    """Add one log line to the running summary."""
    s = SUMMARY
    s["since"] = s["since"] or entry["timestamp"]
    s["last"] = entry["timestamp"]
    if entry.get("status") == 422:
        s["rejected"] += 1
        return
    if entry.get("row", 0) == 0:
        s["requests"][entry["endpoint"]] += 1
        _latency.append(entry["latency_ms"])
    kind = entry["endpoint"].split("/")[1]
    s["predictions"][kind] += 1
    if entry["has_drift"]:
        s["with_drift"] += 1
        s["drift_by_input"].update(entry["drift_inputs"])
    out = entry["outputs"]
    if kind == "freight":
        s["fair_sum"] += out["fair_freight"]
        if out.get("verdicts"):
            s["with_charge"] += 1
            for rule, v in out["verdicts"].items():
                s["unusual"][f"{rule}:{v}"] += 1
    else:
        s["risk_sum"] += out["risk"]
        s["on_list"] += int(out["on_review_list"])
        s["follow_ups"][out["suggested_follow_up"]] += 1


def write_log(entries):
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    text = "".join(json.dumps(e, ensure_ascii=False) + "\n" for e in entries)
    with _lock:
        with open(LOG_FILE, "a", encoding="utf-8") as f:
            f.write(text)
        for e in entries:
            _absorb(e)


def log_predictions(endpoint, request_id, inputs, preds, latency_ms, keep):
    ts = datetime.now(timezone.utc).isoformat(timespec="milliseconds")
    entries = []
    for i, (x, p) in enumerate(zip(inputs, preds)):
        drift_inputs = p.pop("_drift")
        entries.append(dict(timestamp=ts, request_id=request_id, endpoint=endpoint, row=i, input=x.model_dump(),
                            outputs={k: p[k] for k in keep} | (
                                {"verdicts": {r: c["verdict"] for r, c in p["check"]["rules"].items()}}
                                if p.get("check") else {}),
                            has_drift=bool(drift_inputs), drift_inputs=drift_inputs,
                            drift_warnings=p["drift_warnings"], latency_ms=latency_ms))
    write_log(entries)


def _load_existing_log():
    """Seed the summary from an existing log (a restart without a redeploy keeps the file)."""
    if LOG_FILE.exists():
        with open(LOG_FILE, encoding="utf-8") as f:
            for line in f:
                try:
                    _absorb(json.loads(line))
                except (ValueError, KeyError):
                    continue


_load_existing_log()

