@app.exception_handler(RequestValidationError)
async def validation_error(request: Request, exc: RequestValidationError):
    """422 with the standard FastAPI detail plus one readable line per problem."""
    errors, detail = [], []
    for e in exc.errors():
        loc = ".".join(str(p) for p in e["loc"] if p not in ("body", "query"))
        msg = e["msg"].removeprefix("Value error, ")
        if e["type"] == "too_long":
            msg += f": split the rows into batches of at most {MAX_BATCH:,}"
        errors.append(f"{loc}: {msg}" if loc else msg)
        detail.append({k: e[k] for k in ("type", "loc", "msg")})
    write_log([dict(timestamp=datetime.now(timezone.utc).isoformat(timespec="milliseconds"),
                    endpoint=request.url.path, status=422, errors=errors[:20])])
    return JSONResponse(status_code=422, content={"detail": detail, "errors": errors,
                                                  "hint": "See /docs for the expected fields and their ranges."})


