def _zip(v):
    """A Brazilian CEP (01310-100) or its first five digits (01310) -> the five-digit prefix as text."""
    if isinstance(v, float):                       # a number read from a spreadsheet: 1310.0
        if v != v:
            return None
        v = int(v)
    if v is None or str(v).strip() == "":
        return None
    digits = re.sub(r"\D", "", str(v))
    if len(digits) in (4, 5):                      # a prefix; 4 digits = its leading zero was dropped
        prefix = int(digits)
    elif len(digits) in (7, 8):                    # a full CEP, with or without its leading zero
        prefix = int(digits.zfill(8)[:5])
    else:
        raise ValueError(f"'{v}' is not a zip code: give the CEP (e.g. 01310-100) or its first five digits (01310)")
    if prefix < 1000:
        raise ValueError(f"'{v}' is not a Brazilian zip code (prefixes run from 01000 to 99999)")
    return f"{prefix:05d}"


class Route(BaseModel):
    """Where the parcel goes. States are required; zip codes place each party more precisely."""
    model_config = ConfigDict(extra="allow")

    seller_state: str = Field(..., description="Seller's state: a two-letter code such as SP", examples=["SP"])
    customer_state: str = Field(..., description="Customer's state: a two-letter code such as RJ", examples=["RJ"])
    seller_zip: Optional[str] = Field(None, description="Seller's zip code (CEP) or its first five digits",
                                      examples=["01310"])
    customer_zip: Optional[str] = Field(None, description="Customer's zip code (CEP) or its first five digits",
                                        examples=["20040-020"])
    distance_km: Optional[float] = Field(
        None, ge=0, le=5000,
        description="Distance from seller to customer in km. Leave it out to derive it from the zip codes (or the "
                    "state centres); send null to leave it unknown, as for records whose zip code is not in the Olist "
                    "table: the models then use the training median.")

    @field_validator("seller_state", "customer_state", mode="before")
    @classmethod
    def _state(cls, v):
        s = str(v).strip().upper()
        if s not in STATE_CENTRE:
            raise ValueError(f"'{v}' is not a Brazilian state code (two letters, such as SP; see /model-info)")
        return s

    @field_validator("seller_zip", "customer_zip", mode="before")
    @classmethod
    def _zips(cls, v):
        return _zip(v)

    @field_validator("id", mode="before", check_fields=False)
    @classmethod
    def _id(cls, v):
        return None if v is None else str(v)


class FreightItem(Route):
    """One order item, as at checkout. Units: R$, kg, cm3, km."""
    model_config = ConfigDict(extra="allow", json_schema_extra={"examples": [
        {"id": "listing-1", "category": "bed_bath_table", "price": 120.0, "weight_kg": 1.5, "volume_cm3": 9000,
         "seller_state": "SP", "customer_state": "RJ", "seller_zip": "01310", "customer_zip": "20040",
         "n_items": 1, "n_sellers": 1, "freight_value": 35.0}]})

    id: Optional[str] = Field(None, max_length=100, description="Your reference for the row, echoed back")
    category: str = Field("unknown", max_length=80, description="Product category, as in the Olist data "
                          "(e.g. bed_bath_table); unseen categories are treated as rare ones")
    price: float = Field(..., gt=0, le=100_000, description="Item price (R$)")
    weight_kg: float = Field(..., ge=0, le=500, description="Item weight (kg)")
    volume_cm3: float = Field(..., gt=0, le=5_000_000, description="Package volume, length x width x height (cm3)")
    n_items: int = Field(1, ge=1, le=100, description="Items in the order")
    n_sellers: int = Field(1, ge=1, le=20, description="Sellers in the order")
    freight_value: Optional[float] = Field(None, ge=0, le=10_000, description="Freight charged (R$). Optional: when "
                                           "given, the response checks whether the charge is unusual")

    @field_validator("category", mode="before")
    @classmethod
    def _category(cls, v):
        return str(v).strip() if v is not None and str(v).strip() else "unknown"

    @model_validator(mode="after")
    def _basket(self):
        if self.n_sellers > self.n_items:
            raise ValueError("n_sellers cannot exceed n_items")
        return self


