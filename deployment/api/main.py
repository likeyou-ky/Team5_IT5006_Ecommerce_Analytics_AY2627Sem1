_band_upper = [np.inf if b["upper"] is None else b["upper"] for b in FR["price_bands"]]
_audit_edges = [0] + FLAG["band_edges"] + [np.inf]


def score_freight(items):
    routes = [resolve_route(it) for it in items]
    rows = [dict(weight_kg=it.weight_kg, volume_cm3=it.volume_cm3, chargeable_kg=max(it.weight_kg, it.volume_cm3 / 5000),
                 price=it.price, n_items=it.n_items, n_sellers=it.n_sellers, category=it.category, **rt)
            for it, (rt, _) in zip(items, routes)]
    X = model_frame(rows, FR["columns"])
    fair = np.clip(np.expm1(FOREST.predict(X)), 0, None)
    fair_r = np.clip(np.expm1(RIDGE.predict(X)), 0, None)
    t = FR["tariff"]
    tariff = np.maximum(0.0, t["base"] + t["per_kg"] * X.chargeable_kg + t["per_100km"] * X.distance_km / 100
                        + t["same_state"] * X.same_state).to_numpy()
    band_i = np.searchsorted(_band_upper, X.price.to_numpy(), side="right")     # first band whose upper edge > price
    audit = pd.cut(X.price, _audit_edges, labels=FLAG["band_labels"], right=False).astype(str).to_numpy()
    flagged, warnings = drift(X, "freight")
    rare = rare_notes(X, "freight")
    inputs = X.drop(columns=["order_id", "purchase_ts"]).to_dict("records")
    out = []
    for i, it in enumerate(items):
        band = FR["price_bands"][band_i[i]]
        check = None
        if it.freight_value is not None:
            charged = float(it.freight_value)
            rules = {}
            for rule, label in RULES.items():
                hits = {}
                for name, f in (("model", fair[i]), ("ridge", fair_r[i])):
                    cut = FLAG["cuts"][name]
                    thr = cut["overall"] if rule == "overall" else cut["band"][audit[i]]
                    hits[name] = bool(np.log1p(charged) - np.log1p(f) >= thr - FLAG["tol"])   # tolerance: build_models.py
                verdict = ("unusual_both" if hits["model"] and hits["ridge"] else
                           "unusual_forest_only" if hits["model"] else "normal")
                rules[rule] = dict(label=label, forest=hits["model"], ridge=hits["ridge"], verdict=verdict)
            check = dict(charged=charged, excess=charged - float(fair[i]),
                         markup=charged / float(fair[i]) if fair[i] > 0 else None,
                         log_ratio=float(np.log1p(charged) - np.log1p(fair[i])), audit_band=audit[i], rules=rules)
        out.append(dict(
            id=it.id, fair_freight=float(fair[i]), fair_freight_ridge=float(fair_r[i]),
            quote_low=max(0.0, float(fair[i]) - band["mae"]), quote_high=float(fair[i]) + band["mae"],
            price_band=band["band"], band_mae=band["mae"], tariff=plain(tariff[i]), check=check,
            inputs={c: plain(v) for c, v in inputs[i].items()},
            notes=routes[i][1] + rare[i], drift_warnings=warnings[i], _drift=flagged[i]))
    return out


# ------------------------------------------------------------------ Problem 2 scoring
def score_late(orders, share):
    routes = [resolve_route(o) for o in orders]
    rows = [dict(promised_days=o.promised_days, price_total=o.price_total, freight_total=o.freight_total,
                 freight_ratio=o.freight_total / o.price_total, n_items=o.n_items, n_sellers=o.n_sellers, **rt)
            for o, (rt, _) in zip(orders, routes)]
    X = model_frame(rows, LT["columns"])
    risk = LOGIT.predict_proba(X)[:, 1]
    pct = np.interp(risk, LT["score_pct"], np.linspace(0, 100, 101))
    contrib = ((PREP_B.transform(X) - REF_B) * COEF_B) @ GROUP_B                    # (rows, inputs)
    groups = contrib @ ACTION_B
    flagged, warnings = drift(X, "late")
    rare = rare_notes(X, "late")
    inputs = X.drop(columns=["order_id", "purchase_ts"]).to_dict("records")
    out = []
    for i, o in enumerate(orders):
        g = int(groups[i].argmax())
        action = ACTIONS[ACTION_GROUPS[g] if groups[i, g] > 0 else None]
        top = int(contrib[i].argmax())
        out.append(dict(
            id=o.id, risk=float(risk[i]), percentile=float(pct[i]), on_review_list=bool(pct[i] >= 100 * (1 - share)),
            drivers={d: float(v) for d, v in zip(DRIVERS, contrib[i])},
            top_driver=DRIVERS[top] if contrib[i, top] > 0 else None, suggested_follow_up=action,
            inputs={c: plain(v) for c, v in inputs[i].items()},
            notes=routes[i][1] + rare[i], drift_warnings=warnings[i], _drift=flagged[i]))
    return out


